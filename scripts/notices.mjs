import fs from "node:fs/promises";
import path from "node:path";
import { createRequire } from "node:module";
import { root } from "./repository-files.mjs";

const visited = new Set();
const sections = [];
async function visit(name, parent) {
  const require = createRequire(path.join(parent, "package.json"));
  let directory;
  for (const location of require.resolve.paths(name) || []) {
    try {
      await fs.access(path.join(location, name, "package.json"));
      directory = path.join(location, name);
      break;
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }
  if (!directory) throw Error(`Dipendenza non installata: ${name}`);
  const pkg = JSON.parse(
    await fs.readFile(path.join(directory, "package.json"), "utf8"),
  );
  const key = `${pkg.name}@${pkg.version}`;
  if (visited.has(key)) return;
  visited.add(key);
  const names = (await fs.readdir(directory))
    .filter((file) =>
      /^(?:licen[sc]e|copying|notice|copyright)(?:[.-]|$)/i.test(file),
    )
    .sort();
  const texts = [];
  for (const file of names) {
    if ((await fs.stat(path.join(directory, file))).isFile())
      texts.push(
        `${file}\n${await fs.readFile(path.join(directory, file), "utf8")}`,
      );
  }
  if (!texts.length)
    throw Error(
      `Testo licenza assente per ${key}; verifica manuale necessaria`,
    );
  sections.push({
    key,
    text: `${key}\nLicense: ${pkg.license || "See original notices"}\n\n${texts.join("\n\n")}`,
  });
  for (const dependency of Object.keys(pkg.dependencies || {}).sort())
    await visit(dependency, directory);
}
const pkg = JSON.parse(
  await fs.readFile(path.join(root, "package.json"), "utf8"),
);
for (const name of Object.keys(pkg.dependencies).sort())
  await visit(name, root);
await fs.mkdir(path.join(root, "build"), { recursive: true });
await fs.writeFile(
  path.join(root, "build/THIRD_PARTY_LICENSES.txt"),
  (
    "EasyFonts — production npm dependencies\nGenerated by npm run notices. Original public attributions follow.\n\n" +
    sections
      .sort((a, b) => a.key.localeCompare(b.key, "en"))
      .map((section) => section.text)
      .join("\n\n" + "=".repeat(72) + "\n\n")
  )
    .replace(/\r\n/g, "\n")
    .trimEnd() + "\n",
);
console.log(`Avvisi generati: ${sections.length} dipendenze di produzione.`);
